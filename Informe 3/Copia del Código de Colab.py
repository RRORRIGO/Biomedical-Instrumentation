import wfdb
import numpy as np
import matplotlib.pyplot as plt
carpeta = "grabmyo/1.1.0/Session1/session1_participant1"
gestos = {"Reposo": 17, "Cierre de mano": 16, "Extensión del índice": 9}
canal = 11 # canal F12 → índice 11 en Python
senales = {}
for nombre_g, k in gestos.items():
 rec = wfdb.rdrecord(f"session1_participant1_gesture{k}_trial1", pn_dir=carpeta)
 senales[nombre_g] = rec.p_signal[:, canal]
fig, ax = plt.subplots(3, 1, sharex=True, sharey=True)
for a, (nombre_g, x) in zip(ax, senales.items()):
 a.plot(np.arange(len(x)) / rec.fs, x)
 a.set_title(nombre_g)
 a.set_ylabel("mV")
ax[-1].set_xlabel("Tiempo (s)")
plt.show()

secuencia = np.concatenate([
    senales["Reposo"],
    senales["Cierre de mano"],
    senales["Extensión del índice"]
])

print("Número de muestras:", len(secuencia))

minimo = np.min(secuencia)
maximo = np.max(secuencia)

secuencia_escalada = 255 * (secuencia - minimo) / (maximo - minimo)

secuencia_escalada = secuencia_escalada.astype(np.uint8)

print("Mínimo:", secuencia_escalada.min())
print("Máximo:", secuencia_escalada.max())
print("Número de muestras:", len(secuencia_escalada))

tiempo = np.arange(len(secuencia_escalada)) / 2048

plt.figure(figsize=(14,5))

plt.plot(tiempo, secuencia_escalada)

plt.xlabel("Tiempo (s)")
plt.ylabel("Valor DAC")
plt.title("Secuencia sEMG escalada")

plt.show()

with open("semg.h", "w") as f:

    f.write("#include <stdint.h>\n\n")

    f.write("const uint8_t SEMG[] = {\n")

    for i, valor in enumerate(secuencia_escalada):

        f.write(str(valor))

        if i < len(secuencia_escalada) - 1:
            f.write(",")

        if (i + 1) % 20 == 0:
            f.write("\n")

    f.write("\n};\n\n")

    f.write(f"const unsigned int N_SEMG = {len(secuencia_escalada)};\n")

    f.write("const unsigned int FS_SEMG = 2048;\n")

